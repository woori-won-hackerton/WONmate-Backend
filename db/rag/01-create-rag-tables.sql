-- Run with psql -v ON_ERROR_STOP=1 -f db/rag/01-create-rag-tables.sql
-- Requires the existing public.insurance_products(product_id bigint).
-- Existing RAG tables cause an error and rollback; never overwrite existing data.
BEGIN;
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE public.product_documents (
    document_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id bigint NOT NULL,
    document_name varchar(255) NOT NULL,
    document_type varchar(20) NOT NULL,
    storage_url text NOT NULL,
    file_hash varchar(64) NOT NULL,
    ingestion_status varchar(20) NOT NULL DEFAULT 'PENDING',
    embedding_model varchar(255),
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_product_documents_product FOREIGN KEY (product_id)
        REFERENCES public.insurance_products(product_id),
    CONSTRAINT ck_product_documents_type CHECK (document_type IN ('TERMS', 'SUMMARY')),
    CONSTRAINT ck_product_documents_status CHECK (ingestion_status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED')),
    CONSTRAINT ck_product_documents_hash CHECK (file_hash ~ '^[0-9a-fA-F]{64}$')
);
CREATE INDEX ix_product_documents_product ON public.product_documents(product_id);

CREATE TABLE public.product_chunks (
    chunk_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id bigint NOT NULL,
    content text NOT NULL,
    embedding vector(1536),
    start_page integer NOT NULL,
    end_page integer NOT NULL,
    chunk_index integer NOT NULL,
    section_title text,
    section_path text,
    CONSTRAINT fk_product_chunks_document FOREIGN KEY (document_id)
        REFERENCES public.product_documents(document_id),
    CONSTRAINT uk_product_chunks_document_index UNIQUE (document_id, chunk_index),
    CONSTRAINT ck_product_chunks_pages CHECK (start_page >= 1 AND end_page >= start_page),
    CONSTRAINT ck_product_chunks_index CHECK (chunk_index >= 0)
);
COMMIT;
