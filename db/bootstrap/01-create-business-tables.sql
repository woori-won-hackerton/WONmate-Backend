CREATE TABLE public.consultation_preparations (consultation_id bigint not null unique, preparation_id bigint generated by default as identity, summary_briefing text, primary key (preparation_id));

CREATE TABLE public.consultations (confirmed_at timestamptz, consultation_id bigint generated by default as identity, fc_customer_id bigint not null, scheduled_at timestamptz, memo text, purpose text, ai_record jsonb, status consultation_status not null, primary key (consultation_id));

CREATE TABLE public.contracts (actual_premium numeric(15,2) not null, maturity_date date, start_date date not null, contract_id bigint generated by default as identity, fc_customer_id bigint not null, product_id bigint not null, status contract_status not null, primary key (contract_id), check ((actual_premium >= 0) AND (maturity_date IS NULL OR maturity_date >= start_date)));

CREATE TABLE public.customer_wikis (created_at timestamp(6), customer_id bigint not null unique, updated_at timestamp(6), wiki_id bigint generated by default as identity, content text not null, primary key (wiki_id));

CREATE TABLE public.customers (birth_date date, has_children boolean, has_disability boolean, is_married boolean, customer_id bigint generated by default as identity, phone_number varchar(30), full_name varchar(100) not null, occupation varchar(100), residential_area varchar(200), gender gender_code, primary key (customer_id));

CREATE TABLE public.expected_questions (preparation_id bigint not null, question_id bigint generated by default as identity, answer text, question text not null, primary key (question_id));

CREATE TABLE public.fc_customers (customer_id bigint not null, fc_customer_id bigint generated by default as identity, fc_id bigint not null, assignment_status assignment_status not null, primary key (fc_customer_id), unique (fc_id, customer_id));

CREATE TABLE public.financial_consultants (joined_year smallint, fc_id bigint generated by default as identity, branch_name varchar(100), full_name varchar(100) not null, login_id varchar(100) not null unique, email varchar(254) not null unique, password_hash varchar(255) not null, primary key (fc_id), check ((joined_year IS NULL OR joined_year BETWEEN 1900 AND 9999)));

CREATE TABLE public.insurance_products (base_premium numeric(15,2), payment_term_months integer, product_id bigint generated by default as identity, insurance_type varchar(50) not null, eligible_age_description varchar(200), product_name varchar(200) not null, payment_frequency payment_frequency, primary key (product_id), check ((base_premium IS NULL OR base_premium >= 0) AND (payment_term_months IS NULL OR payment_term_months > 0)));

CREATE TABLE public.todos (due_date date, is_completed boolean not null, fc_id bigint not null, todo_id bigint generated by default as identity, content text not null, primary key (todo_id));

