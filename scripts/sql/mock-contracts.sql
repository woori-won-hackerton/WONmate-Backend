-- 1. FC/고객/담당 관계/상품/계약의 목업 데이터를 모두 생성합니다.
--    프로젝트의 DB enum 6종과 필요한 다섯 엔티티의 테이블이 없으면 먼저 생성합니다.
--    기존 타입/테이블은 변경하지 않습니다. 상담/문서 테이블은 생성하지 않습니다.
--    vector 확장은 별도입니다. vector 타입 오류가 있으면 pgvector 설치 후
--    대상 DB에서 CREATE EXTENSION IF NOT EXISTS vector; 를 실행하세요.
-- 2. 목업 FC 로그인: mock_contract_fc / MockFc123!
--    비밀번호는 Spring BCryptPasswordEncoder로 생성/검증한 해시를 저장합니다.
--    동일 login_id가 다른 계정에 사용 중이면 해당 계정을 변경하지 않고 중단합니다.
-- 3. 파일 전체를 실행하세요. 실패하면 ROLLBACK 후 원인을 해결하세요.
--    Spring Boot가 자동 실행하지 않는 수동 실행용 파일입니다.
-- 4. 같은 FC로 순차 재실행하면 동일한 목업 고객/상품/계약을 재사용합니다.
--    [MOCK-CONTRACT] 이름은 이 파일 전용입니다. 동시에 실행하지 마세요.
--
-- 예상 결과 (선택한 FC의 JWT 사용):
--   계약목록 고객: 200, 계약 4건 (모든 상태 포함)
--   계약없음 고객: 200, result: []
--   담당해제 고객: 403
--   담당 관계가 없는 다른 FC의 JWT로 위 고객 조회: 403
--   연납 계약의 monthlyPremium: null

BEGIN;

-- 현재 엔티티에 명시된 PostgreSQL 타입만 준비합니다.
DO $$
    BEGIN
        IF to_regtype('consultation_status') IS NULL THEN
            CREATE TYPE consultation_status AS ENUM ('draft', 'scheduled', 'completed', 'cancelled');
        END IF;
        IF to_regtype('document_type') IS NULL THEN
            CREATE TYPE document_type AS ENUM ('terms', 'brochure', 'product_summary', 'other');
        END IF;
        IF to_regtype('gender_code') IS NULL THEN
            CREATE TYPE gender_code AS ENUM ('male', 'female', 'other');
        END IF;
        IF to_regtype('assignment_status') IS NULL THEN
            CREATE TYPE assignment_status AS ENUM ('active', 'inactive');
        END IF;
        IF to_regtype('payment_frequency') IS NULL THEN
            CREATE TYPE payment_frequency AS ENUM ('monthly', 'quarterly', 'semiannual', 'annual', 'single');
        END IF;
        IF to_regtype('contract_status') IS NULL THEN
            CREATE TYPE contract_status AS ENUM ('active', 'lapsed', 'terminated', 'matured');
        END IF;
    END;
$$;

CREATE TABLE IF NOT EXISTS financial_consultants (
                                                     fc_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                     login_id varchar(100) NOT NULL UNIQUE,
                                                     password varchar(255) NOT NULL,
                                                     email varchar(254) NOT NULL UNIQUE,
                                                     full_name varchar(100) NOT NULL,
                                                     joined_year smallint,
                                                     branch_name varchar(100),
                                                     created_at timestamp(6),
                                                     updated_at timestamp(6),
                                                     CHECK (joined_year IS NULL OR joined_year BETWEEN 1900 AND 9999)
);

CREATE TABLE IF NOT EXISTS customers (
                                         customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         full_name varchar(100) NOT NULL,
                                         birth_date date,
                                         gender gender_code,
                                         occupation varchar(100),
                                         is_married boolean,
                                         has_children boolean,
                                         has_disability boolean,
                                         phone_number varchar(30),
                                         residential_area varchar(200),
                                         created_at timestamp(6),
                                         updated_at timestamp(6)
);

CREATE TABLE IF NOT EXISTS fc_customers (
                                            fc_customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                            customer_id bigint NOT NULL REFERENCES customers(customer_id),
                                            fc_id bigint NOT NULL REFERENCES financial_consultants(fc_id),
                                            assignment_status assignment_status NOT NULL,
                                            created_at timestamp(6),
                                            updated_at timestamp(6),
                                            UNIQUE (fc_id, customer_id)
);

CREATE TABLE IF NOT EXISTS insurance_products (
                                                  product_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                                  product_name varchar(200) NOT NULL,
                                                  payment_term_months integer,
                                                  base_premium numeric(15, 2),
                                                  insurance_type varchar(50) NOT NULL,
                                                  eligible_age_description varchar(200),
                                                  payment_frequency payment_frequency,
                                                  created_at timestamp(6),
                                                  updated_at timestamp(6),
                                                  CHECK ((base_premium IS NULL OR base_premium >= 0)
                                                      AND (payment_term_months IS NULL OR payment_term_months > 0))
);

CREATE TABLE IF NOT EXISTS contracts (
                                         contract_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         fc_customer_id bigint NOT NULL REFERENCES fc_customers(fc_customer_id),
                                         product_id bigint NOT NULL REFERENCES insurance_products(product_id),
                                         actual_premium numeric(15, 2) NOT NULL,
                                         start_date date NOT NULL,
                                         maturity_date date,
                                         status contract_status NOT NULL,
                                         created_at timestamp(6),
                                         updated_at timestamp(6),
                                         CHECK ((actual_premium >= 0)
                                             AND (maturity_date IS NULL OR maturity_date >= start_date))
);

CREATE TEMP TABLE mock_contract_result (
                                           scenario text,
                                           customer_id bigint,
                                           fc_customer_id bigint
) ON COMMIT DROP;

DO $$
    DECLARE
        v_fc_login_id text := 'mock_contract_fc';
        v_fc_id bigint;
        v_customer_id bigint;
        v_fc_customer_id bigint;
        v_product_id bigint;
        v_name text;
        v_scenario text;
        v_product record;
    BEGIN
        IF EXISTS (
            SELECT 1 FROM financial_consultants
            WHERE login_id = v_fc_login_id
              AND (email <> 'mock-contract-fc@example.com' OR full_name <> '[MOCK-CONTRACT] 테스트 FC')
        ) THEN
            RAISE EXCEPTION '목업 login_id가 다른 계정에 사용 중입니다: %', v_fc_login_id;
        END IF;

        INSERT INTO financial_consultants (
            login_id, password, email, full_name, joined_year, branch_name, created_at, updated_at
        ) VALUES (
                     v_fc_login_id,
                     '$2a$10$m0FymkrCzMqoMEgnQpULP.G3v8JKcix8MMfu2qalwcBe0dzDZG1iK',
                     'mock-contract-fc@example.com', '[MOCK-CONTRACT] 테스트 FC', 2020, '목업 지점',
                     CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
                 ) ON CONFLICT (login_id) DO NOTHING;

        SELECT fc_id INTO v_fc_id
        FROM financial_consultants
        WHERE login_id = v_fc_login_id;

        FOREACH v_scenario IN ARRAY ARRAY['계약목록', '계약없음', '담당해제'] LOOP
                v_name := '[MOCK-CONTRACT] FC ' || v_fc_id || ' ' || v_scenario;

                IF (SELECT count(*) FROM customers WHERE full_name = v_name) > 1 THEN
                    RAISE EXCEPTION '동일한 목업 이름의 고객이 중복되어 있습니다: %', v_name;
                END IF;

                SELECT customer_id INTO v_customer_id FROM customers WHERE full_name = v_name;
                IF v_customer_id IS NULL THEN
                    INSERT INTO customers (
                        full_name, birth_date, gender, occupation,
                        is_married, has_children, has_disability,
                        phone_number, residential_area, created_at, updated_at
                    ) VALUES (
                                 v_name, DATE '1984-05-15', 'male', 'IT 회사 팀장',
                                 true, true, false, '010-0000-0000', '서울특별시 마포구',
                                 CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
                             ) RETURNING customer_id INTO v_customer_id;
                END IF;

                INSERT INTO fc_customers (
                    fc_id, customer_id, assignment_status, created_at, updated_at
                ) VALUES (
                             v_fc_id, v_customer_id, 'active', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
                         )
                ON CONFLICT (fc_id, customer_id) DO NOTHING;

                -- 이 파일 전용 목업 고객의 담당 상태만 설정합니다.
                IF v_scenario = '담당해제' THEN
                    UPDATE fc_customers SET assignment_status = 'inactive', updated_at = CURRENT_TIMESTAMP
                    WHERE fc_id = v_fc_id AND customer_id = v_customer_id;
                ELSE
                    UPDATE fc_customers SET assignment_status = 'active', updated_at = CURRENT_TIMESTAMP
                    WHERE fc_id = v_fc_id AND customer_id = v_customer_id;
                END IF;

                SELECT fc_customer_id INTO v_fc_customer_id
                FROM fc_customers WHERE fc_id = v_fc_id AND customer_id = v_customer_id;

                INSERT INTO mock_contract_result VALUES (v_scenario, v_customer_id, v_fc_customer_id);
            END LOOP;

        SELECT fc_customer_id INTO v_fc_customer_id
        FROM mock_contract_result WHERE scenario = '계약목록';

        FOR v_product IN
            SELECT * FROM (VALUES
                               ('[MOCK-CONTRACT] 건강보험', '건강', 'monthly', 35000.00, 'active', DATE '2026-01-01', DATE '2046-01-01'),
                               ('[MOCK-CONTRACT] 암보험', '암', 'monthly', 48000.00, 'lapsed', DATE '2025-06-15', DATE '2045-06-15'),
                               ('[MOCK-CONTRACT] 상해보험', '상해', 'monthly', 22000.00, 'terminated', DATE '2024-03-01', DATE '2034-03-01'),
                               ('[MOCK-CONTRACT] 연납보험', '건강', 'annual', 360000.00, 'matured', DATE '2016-01-01', DATE '2026-01-01')
                          ) AS fixtures(product_name, insurance_type, frequency, premium, status, start_date, maturity_date)
            LOOP
                IF (SELECT count(*) FROM insurance_products WHERE product_name = v_product.product_name) > 1 THEN
                    RAISE EXCEPTION '동일한 목업 상품명이 중복되어 있습니다: %', v_product.product_name;
                END IF;

                SELECT product_id INTO v_product_id
                FROM insurance_products WHERE product_name = v_product.product_name;

                IF v_product_id IS NULL THEN
                    INSERT INTO insurance_products (
                        product_name, insurance_type, payment_term_months, base_premium,
                        eligible_age_description, payment_frequency, created_at, updated_at
                    ) VALUES (
                                 v_product.product_name, v_product.insurance_type, 240, v_product.premium,
                                 '테스트용 상품', v_product.frequency::payment_frequency,
                                 CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
                             ) RETURNING product_id INTO v_product_id;
                END IF;

                IF NOT EXISTS (
                    SELECT 1 FROM contracts
                    WHERE fc_customer_id = v_fc_customer_id AND product_id = v_product_id
                ) THEN
                    INSERT INTO contracts (
                        fc_customer_id, product_id, actual_premium, start_date,
                        maturity_date, status, created_at, updated_at
                    ) VALUES (
                                 v_fc_customer_id, v_product_id, v_product.premium, v_product.start_date,
                                 v_product.maturity_date, v_product.status::contract_status,
                                 CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
                             );
                END IF;
            END LOOP;
    END;
$$;

-- 조회 API에 사용할 고객 ID와 예상 응답을 확인합니다.
SELECT fc_id, login_id, full_name
FROM financial_consultants WHERE login_id = 'mock_contract_fc';

SELECT scenario, customer_id, fc_customer_id,
       '/api/contracts/' || customer_id AS api_path,
       CASE WHEN scenario = '담당해제' THEN 403 ELSE 200 END AS expected_http_status
FROM mock_contract_result
ORDER BY customer_id;

SELECT r.customer_id, c.contract_id, p.product_name, c.start_date,
       p.insurance_type, c.status, p.payment_frequency, c.actual_premium,
       CASE WHEN p.payment_frequency = 'monthly' THEN c.actual_premium END AS monthly_premium
FROM mock_contract_result r
         JOIN contracts c ON c.fc_customer_id = r.fc_customer_id
         JOIN insurance_products p ON p.product_id = c.product_id
ORDER BY c.start_date DESC, c.contract_id DESC;

COMMIT;
